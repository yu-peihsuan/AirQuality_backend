def get_rule_by_aqi(aqi_value: int) -> dict | None:
    """根據 AQI 數值回傳對應的健康規則（不含突發事件型規則）。"""
    for rule in AQI_HEALTH_RULES:
        if rule["aqi_range"] is None:
            continue
        lo, hi = rule["aqi_range"]
        if lo <= aqi_value <= hi:
            return rule
    return None


def get_all_rules() -> list[dict]:
    """回傳所有規則（含事件型）"""
    return AQI_HEALTH_RULES


def get_rule_by_id(rule_id: str) -> dict | None:
    """根據 id 回傳完整規則"""
    for rule in AQI_HEALTH_RULES:
        if rule["id"] == rule_id:
            return rule
    return None


def get_sensitive_group_advice(aqi_value: int, group: str) -> str | None:
    """根據 AQI 數值與特定族群，回傳該族群的專屬防護建議。

    group 可為：孕婦、孩童、心肺疾病患者、氣喘患者、高血壓患者、
               糖尿病患者、脂肪肝/肝臟疾病患者、肝臟疾病患者、失智症/高齡者
    """
    rule = get_rule_by_aqi(aqi_value)
    if rule is None:
        return None
    special = rule.get("special_groups", {})
    for key, advice in special.items():
        if group in key or key in group:
            return advice
    return rule.get("advice_sensitive")


