def _number_to_zh(n: int) -> str | None:
    """將整數轉為中文文字（用於大數字的混合數值表示，提升向量化效果）。"""
    if n <= 3000:
        return None

    units  = ["", "十", "百", "千", "萬", "十萬", "百萬", "千萬",
              "億", "十億", "百億", "千億", "兆"]
    digits = ["零", "一", "二", "三", "四", "五", "六", "七", "八", "九"]

    if n == 0:
        return "零"

    result = ""
    str_n = str(n)
    length = len(str_n)
    for i, ch in enumerate(str_n):
        d = int(ch)
        pos = length - i - 1
        if d != 0:
            result += digits[d] + units[pos]
        elif result and result[-1] != "零":
            result += "零"
    result = result.rstrip("零")
    if result.startswith("一十"):
        result = result[1:]
    return result or "零"


def apply_hybrid_number_repr(text: str, threshold: int = 3000) -> str:
    """對文字中的數字套用混合數值表示。

    數字 ≤ threshold：保留原始數字形式；數字 > threshold：轉換為中文文字形式。
    """
    import re

    def replace_num(match: re.Match) -> str:
        num_str = match.group(0).replace(",", "").replace("，", "")
        try:
            n = int(num_str)
        except ValueError:
            return match.group(0)
        if n <= threshold:
            return match.group(0)
        zh = _number_to_zh(n)
        return zh if zh else match.group(0)

    pattern = r"\d[\d,，]*"
    return re.sub(pattern, replace_num, text)


def get_rag_indexing_text(rule_id: str) -> str | None:
    """回傳指定規則 ID 的 RAG indexing 用文字（套用混合數值表示後的版本）。"""
    rule = next((r for r in AQI_HEALTH_RULES if r["id"] == rule_id), None)
    if rule is None:
        return None

    base_text = rule.get("text", "")
    range_text = rule.get("aqi_range_text", "")
    processed = apply_hybrid_number_repr(base_text)

    if range_text:
        return f"{range_text} {processed}"
    return processed